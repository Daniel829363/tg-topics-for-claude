#!/usr/bin/env bun
/**
 * tgt — the tg-topics command line. The plugin's skills call it; so can you.
 *
 *   bun tgt.ts setup [--skip-permissions] [--no-autostart]   install or repair everything
 *   bun tgt.ts status                                         what runs, what's missing
 *   bun tgt.ts start | stop | restart                         the router
 *   bun tgt.ts logs [lines]                                   tail the router log
 *   bun tgt.ts close N | all | <route>                        close a Claude session (N from status)
 *   bun tgt.ts max [N]                                        show / set the parallel session limit
 *   bun tgt.ts autostart on|off                               start the router at Windows sign-in
 *   bun tgt.ts commands [--force]                             sync the bot's command menu now
 *   bun tgt.ts patch | unpatch                                apply / remove the overlay on the official plugin
 *   bun tgt.ts guide [ru|en]                                  terminal-command guide (the bot's /setup)
 *   bun tgt.ts hook-start                                     SessionStart hook: quiet upkeep, never fails
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync, rmSync, copyFileSync } from 'fs'
import { join, resolve } from 'path'
import { spawn } from 'child_process'
import {
  loadConfig, defaultConfig, applyOverlay, removeOverlay, overlayState, installsOf, readToken, routerHttp, secretFile, writeIfChanged, updateConfigFile,
  PLUGIN_ROOT, PLUGIN_VERSION, HOME, CONFIG_FILE, LOG_FILE, CLAUDE_DIR, SESSION_SETTINGS, INSTALLED_PLUGINS, OFFICIAL_KEY,
  type Config,
} from '../lib/common.ts'
import { ensureBotCommands, apiCaller, setupGuide, langOf, COMMANDS_MARKER, MAX_SESSIONS_CAP, type AccessLike } from '../overlay/bot-ui.ts'

const IS_WIN = process.platform === 'win32'
const API_ROOT = (process.env.TELEGRAM_API_ROOT ?? 'https://api.telegram.org').replace(/\/+$/, '')
const LAUNCH_TS = join(HOME, 'launch-router.ts')
const START_VBS = join(HOME, 'start-router.vbs')
const STARTUP_VBS = join(process.env.APPDATA ?? '', 'Microsoft', 'Windows', 'Start Menu', 'Programs', 'Startup', 'tg-router.vbs')
const BAT = join(HOME, 'claude-telegram.bat')

let cfg: Config = loadConfig()
const say = (...lines: string[]) => console.log(lines.join('\n'))
const psq = (s: string) => `'${s.replace(/'/g, "''")}'`

// ---- Router process -----------------------------------------------------------

type Health = { version?: string; pid?: number; bot?: string }

async function health(): Promise<Health | null> {
  try {
    const res = await fetch(`${routerHttp(cfg)}/health`, { signal: AbortSignal.timeout(1500) })
    if (!res.ok) return null
    const body = await res.text()
    try { return JSON.parse(body) } catch { return {} } // pre-tg-topics routers answer a plain "ok"
  } catch {
    return null
  }
}

async function waitFor(up: boolean, ms: number): Promise<boolean> {
  const end = Date.now() + ms
  while (Date.now() < end) {
    if (Boolean(await health()) === up) return true
    await Bun.sleep(300)
  }
  return false
}

/** This plugin's key in installed_plugins.json, e.g. "tg-topics@tg-topics". */
function selfKey(): string {
  const norm = (p: string) => resolve(p).toLowerCase()
  try {
    const reg = JSON.parse(readFileSync(INSTALLED_PLUGINS, 'utf8'))
    for (const [key, list] of Object.entries<any[]>(reg.plugins ?? {})) {
      if (list.some(i => norm(i.installPath) === norm(PLUGIN_ROOT))) return key
    }
  } catch {}
  return 'tg-topics@tg-topics'
}

// Locations a non-default setup may override. The router is started via WMI
// or at sign-in and inherits none of our environment, so they're baked in.
const CARRIED_ENV = ['CLAUDE_CONFIG_DIR', 'TG_ROUTER_HOME', 'TG_ROUTER_CONFIG', 'TG_ROUTER_STATE', 'TG_ROUTER_LOG', 'TELEGRAM_STATE_DIR', 'TELEGRAM_API_ROOT']

// The plugin directory changes with every update; these launchers live in
// HOME and look the current install up at start, so autostart never goes stale.
function launchTs(key: string): string {
  const carried = Object.fromEntries(CARRIED_ENV.filter(k => process.env[k]).map(k => [k, process.env[k]]))
  return `// Generated by tg-topics — starts tg-router from the installed tg-topics plugin.
// The plugin path changes with every update; this file does not.
import { readFileSync, existsSync } from 'fs'
import { join } from 'path'
import { pathToFileURL } from 'url'

Object.assign(process.env, ${JSON.stringify(carried)})
const KEY = ${JSON.stringify(key)}
const REGISTRY = ${JSON.stringify(INSTALLED_PLUGINS)}
let root = ${JSON.stringify(PLUGIN_ROOT)}
try {
  const installs: any[] = JSON.parse(readFileSync(REGISTRY, 'utf8')).plugins?.[KEY] ?? []
  const best = installs
    .filter(i => existsSync(join(i.installPath, 'router', 'router.ts')))
    .sort((a, b) => String(b.lastUpdated ?? '').localeCompare(String(a.lastUpdated ?? '')))[0]
  if (best) root = best.installPath
} catch {}
await import(pathToFileURL(join(root, 'router', 'router.ts')).href)
`
}

function startVbs(): string {
  const q = (s: string) => s.replace(/"/g, '""')
  return [
    "' Generated by tg-topics — starts tg-router hidden (no console window).",
    'Set sh = CreateObject("WScript.Shell")',
    `sh.CurrentDirectory = "${q(HOME)}"`,
    `sh.Run """${q(process.execPath)}"" ""${q(LAUNCH_TS)}""", 0, False`,
    '',
  ].join('\r\n')
}

/** VBScript reads UTF-16 with a BOM reliably — user names may be non-ASCII. */
function writeVbs(file: string, text: string): boolean {
  const buf = Buffer.from('﻿' + text, 'utf16le')
  try { if (Buffer.compare(readFileSync(file), buf) === 0) return false } catch {}
  mkdirSync(resolve(file, '..'), { recursive: true })
  writeFileSync(file, buf)
  return true
}

function writeLaunchers(): void {
  writeIfChanged(LAUNCH_TS, launchTs(selfKey()))
  if (IS_WIN) {
    writeVbs(START_VBS, startVbs())
    // Keep an enabled autostart pointing at the current launcher.
    if (existsSync(STARTUP_VBS)) writeVbs(STARTUP_VBS, startVbs())
  }
}

async function startRouter(): Promise<boolean> {
  if (await health()) return true
  writeLaunchers()
  if (IS_WIN) {
    // WMI creates the process outside this process's job object, so the
    // router outlives the Claude session that started it.
    const ps = `$r = Invoke-CimMethod -ClassName Win32_Process -MethodName Create -Arguments @{ CommandLine = ${psq(`wscript.exe "${START_VBS}"`)}; CurrentDirectory = ${psq(HOME)} }; exit [int]$r.ReturnValue`
    const r = Bun.spawnSync(['powershell.exe', '-NoProfile', '-NonInteractive', '-Command', ps], { stdout: 'ignore', stderr: 'ignore' })
    if (r.exitCode !== 0) spawn(process.execPath, [LAUNCH_TS], { cwd: HOME, detached: true, stdio: 'ignore' }).unref()
  } else {
    spawn(process.execPath, [LAUNCH_TS], { cwd: HOME, detached: true, stdio: 'ignore' }).unref()
  }
  return waitFor(true, 15_000)
}

function routerSecret(): string {
  try { return readFileSync(secretFile(cfg), 'utf8').trim() } catch { return '' }
}

async function stopRouter(): Promise<boolean> {
  if (!(await health())) return true
  const secret = routerSecret()
  try {
    await fetch(`${routerHttp(cfg)}/shutdown`, { method: 'POST', headers: { 'x-tg-router-secret': secret }, signal: AbortSignal.timeout(2000) })
  } catch {}
  if (await waitFor(false, 5000)) return true
  // Routers from before tg-topics have no /shutdown: stop whatever listens on our port.
  if (IS_WIN) {
    Bun.spawnSync(['powershell.exe', '-NoProfile', '-NonInteractive', '-Command',
      `Get-NetTCPConnection -LocalPort ${cfg.port} -State Listen -ErrorAction SilentlyContinue | ForEach-Object { Stop-Process -Id $_.OwningProcess -Force }`,
    ], { stdout: 'ignore', stderr: 'ignore' })
  } else {
    Bun.spawnSync(['sh', '-c', `kill $(lsof -t -iTCP:${cfg.port} -sTCP:LISTEN) 2>/dev/null`])
  }
  return waitFor(false, 5000)
}

// ---- Sessions -------------------------------------------------------------------

async function routerStatus(): Promise<any | null> {
  try { return await (await fetch(`${routerHttp(cfg)}/status`, { signal: AbortSignal.timeout(3000) })).json() } catch { return null }
}

/** Same order as the bot's /sessions, so the numbers match. */
function sessionRoutes(st: any): { route: string; label: string; starting?: boolean }[] {
  const label = (s: any) => (s.route === 'dm' ? 'личка (основная)' : `${s.chat_title ?? ''} / ${s.topic ?? s.route}`)
  return [
    ...(st.sessions ?? []).map((s: any) => ({ route: s.route, label: label(s) })),
    ...(st.starting ?? []).map((r: string) => ({ route: r, label: r, starting: true })),
  ]
}

async function closeSessions(arg: string | undefined): Promise<number> {
  const st = await routerStatus()
  if (!st) { say('❌ роутер не запущен — закрывать нечего'); return 1 }
  const list = sessionRoutes(st)
  let targets: typeof list
  if (arg === 'all') targets = list.filter(s => s.route !== 'dm')
  else if (arg && /^\d+$/.test(arg) && list[Number(arg) - 1]) targets = [list[Number(arg) - 1]!]
  else if (arg && list.some(s => s.route === arg)) targets = list.filter(s => s.route === arg)
  else {
    say('какую сессию закрыть? tgt close N | all | <route>', ...list.map((s, i) => `  ${i + 1}. ${s.starting ? '⏳' : '🟢'} ${s.label}  [${s.route}]`))
    return 1
  }
  targets = targets.filter(s => !s.starting)
  if (!targets.length) { say('нет подходящих запущенных сессий'); return 1 }
  const res = await fetch(`${routerHttp(cfg)}/control`, {
    method: 'POST',
    headers: { 'x-tg-router-secret': routerSecret(), 'content-type': 'application/json' },
    body: JSON.stringify({ stop: targets.map(s => s.route) }),
    signal: AbortSignal.timeout(30_000),
  })
  if (!res.ok) { say(`❌ роутер ответил ${res.status} (старая версия? → /tg-topics:router restart)`); return 1 }
  const closed = new Set(((await res.json()) as { closed: string[] }).closed)
  for (const s of targets) say(closed.has(s.route) ? `⏹ закрыта: ${s.label}` : `⚠️ не закрылась: ${s.label} — закрой вкладку вручную`)
  return targets.every(s => closed.has(s.route)) ? 0 : 1
}

async function maxSessions(arg: string | undefined): Promise<number> {
  if (arg == null) {
    const st = await routerStatus()
    say(`лимит параллельных сессий: ${st?.maxSessions ?? cfg.maxSessions}${st ? `, занято: ${sessionRoutes(st).length}` : ''}`)
    return 0
  }
  const n = Number(arg)
  if (!Number.isInteger(n) || n < 1 || n > MAX_SESSIONS_CAP) { say(`нужно число от 1 до ${MAX_SESSIONS_CAP}`); return 1 }
  if (await health()) {
    const res = await fetch(`${routerHttp(cfg)}/control`, {
      method: 'POST',
      headers: { 'x-tg-router-secret': routerSecret(), 'content-type': 'application/json' },
      body: JSON.stringify({ maxSessions: n }),
      signal: AbortSignal.timeout(5000),
    }).catch(() => null)
    if (res?.ok) {
      const r = (await res.json()) as { old: number }
      say(`✅ лимит сессий: ${r.old} → ${n} (роутер применил сразу)`)
      return 0
    }
  }
  const old = cfg.maxSessions
  updateConfigFile({ maxSessions: n })
  say(`✅ лимит сессий: ${old} → ${n} (записан в ${CONFIG_FILE}; запущенный роутер старой версии подхватит после /tg-topics:router restart)`)
  return 0
}

// ---- Settings -------------------------------------------------------------------

function readJson(file: string): any {
  try { return JSON.parse(readFileSync(file, 'utf8')) } catch { return undefined }
}

function writeJson(file: string, value: unknown): void {
  mkdirSync(resolve(file, '..'), { recursive: true })
  writeFileSync(file, JSON.stringify(value, null, 2) + '\n')
}

function loadAccess(): AccessLike & { allowFrom: string[] } {
  const a = readJson(join(cfg.telegramStateDir, 'access.json')) ?? {}
  return { dmPolicy: a.dmPolicy ?? 'pairing', allowFrom: a.allowFrom ?? [], groups: a.groups ?? {}, pending: a.pending ?? {} }
}

function writeConfig(skipPermissions: boolean): string {
  const existing = readJson(CONFIG_FILE)
  if (existing) {
    if (skipPermissions && !(existing.claudeArgs ?? []).includes('--dangerously-skip-permissions')) {
      existing.claudeArgs = ['--dangerously-skip-permissions', ...(existing.claudeArgs ?? defaultConfig().claudeArgs)]
      writeJson(CONFIG_FILE, existing)
      return 'обновлён (сессии без запросов разрешений)'
    }
    return 'уже есть, не трогаю'
  }
  const d = defaultConfig()
  writeJson(CONFIG_FILE, {
    port: d.port,
    topicsRoot: d.topicsRoot,
    claudeExe: d.claudeExe,
    claudeArgs: skipPermissions ? ['--dangerously-skip-permissions', ...d.claudeArgs] : d.claudeArgs,
    launcher: d.launcher,
    wtWindow: d.wtWindow,
    maxSessions: d.maxSessions,
    spawnTimeoutSec: d.spawnTimeoutSec,
    queueTtlSec: d.queueTtlSec,
    announceSpawn: d.announceSpawn,
    dm: d.dm,
  })
  return 'создан'
}

/**
 * The official plugin's server must run only in channel sessions: one started
 * by an ordinary session would register as the main (dm) route and swallow
 * DMs. So it's enabled through the --settings file the channel sessions use,
 * and disabled for everything else.
 */
function ensurePluginSettings(key: string): string[] {
  const notes: string[] = []
  const session = readJson(SESSION_SETTINGS) ?? {}
  session.enabledPlugins ??= {}
  if (session.enabledPlugins[OFFICIAL_KEY] !== true || session.enabledPlugins[key] !== true) {
    session.enabledPlugins[OFFICIAL_KEY] = true
    session.enabledPlugins[key] = true
    writeJson(SESSION_SETTINGS, session)
    notes.push(`включил telegram и ${key} для Telegram-сессий (${SESSION_SETTINGS})`)
  }
  const userFile = join(CLAUDE_DIR, 'settings.json')
  const user = readJson(userFile)
  if (user?.enabledPlugins?.[OFFICIAL_KEY] === true) {
    user.enabledPlugins[OFFICIAL_KEY] = false
    writeJson(userFile, user)
    notes.push(`выключил telegram в обычных сессиях (${userFile}) — иначе любая сессия перехватывала бы личку бота`)
  }
  return notes
}

function writeBat(): string | undefined {
  const quote = (s: string) => (/[\s"]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s)
  const bat = [
    '@echo off',
    'rem Generated by tg-topics: the main Telegram session of Claude Code.',
    `cd /d ${quote(cfg.dm.dir)}`,
    `${quote(cfg.claudeExe)} ${[...cfg.claudeArgs, '-n', 'TG: DM'].map(quote).join(' ')}`,
    '',
  ].join('\r\n')
  writeIfChanged(BAT, bat)
  // A copy on the desktop, unless one is already there.
  const r = Bun.spawnSync(['powershell.exe', '-NoProfile', '-NonInteractive', '-Command', "[Environment]::GetFolderPath('Desktop')"])
  const desktop = r.stdout.toString().trim()
  if (!desktop) return undefined
  const target = join(desktop, 'claude-telegram.bat')
  if (existsSync(target)) return target
  copyFileSync(BAT, target)
  return target
}

// ---- Commands ---------------------------------------------------------------------

async function botName(token: string): Promise<string | null> {
  try { return (await apiCaller(API_ROOT, token)('getMe', {})).username } catch { return null }
}

async function syncCommands(force: boolean): Promise<string> {
  const token = readToken(cfg)
  if (!token) return '❌ токен не задан'
  const r = await ensureBotCommands(apiCaller(API_ROOT, token), cfg.telegramStateDir, { force })
  return r.changed ? `✅ меню команд записано для @${r.username} (${r.reason})` : `✅ меню команд @${r.username} актуально`
}

async function setup(args: string[]): Promise<number> {
  const skipPermissions = args.includes('--skip-permissions')
  const noAutostart = args.includes('--no-autostart')
  say(`tg-topics ${PLUGIN_VERSION} — установка`)

  if (!installsOf(OFFICIAL_KEY).length) {
    say('❌ Не установлен официальный плагин telegram. Сначала: /plugin install telegram@claude-plugins-official')
    return 1
  }

  for (const r of applyOverlay(cfg)) {
    say(r.error ? `❌ оверлей ${r.dir}: ${r.error}` : `✅ плагин telegram ${r.version ?? ''}: оверлей ${r.changed ? 'применён' : 'уже применён'}`)
  }

  say(`✅ конфиг роутера ${writeConfig(skipPermissions)}: ${CONFIG_FILE}`)
  cfg = loadConfig()
  mkdirSync(cfg.topicsRoot, { recursive: true })

  for (const n of ensurePluginSettings(selfKey())) say(`✅ ${n}`)

  writeLaunchers()
  if (IS_WIN) {
    const desktop = writeBat()
    say(`✅ запуск основной сессии: ${BAT}${desktop ? ` (ярлык: ${desktop})` : ''}`)
    if (noAutostart) {
      say('— автозапуск роутера не включаю (--no-autostart)')
    } else {
      writeVbs(STARTUP_VBS, startVbs())
      say('✅ автозапуск роутера при входе в Windows')
    }
  }

  const token = readToken(cfg)
  if (!token) {
    say('', '⚠️ Токен бота не задан. Выполни /telegram:configure <токен от @BotFather>, затем снова /tg-topics:setup')
    return 0
  }
  const name = await botName(token)
  if (!name) {
    say('❌ Telegram не принял токен (или нет сети). Проверь: /telegram:configure')
    return 1
  }
  say(`✅ бот @${name}`)
  try { say(await syncCommands(false)) } catch (err) { say(`⚠️ меню команд: ${err}`) }

  await stopRouter()
  say((await startRouter()) ? '✅ роутер запущен' : `❌ роутер не запустился — смотри ${LOG_FILE}`)

  const access = loadAccess()
  say('', 'Дальше:')
  if (!access.allowFrom.length) {
    say(`1. Напиши боту @${name} в Telegram команду /id — он пришлёт твой ID и готовую команду.`)
    say('2. Введи её в терминале Claude Code с Telegram: /telegram:access allow <ID>')
    say('3. Закрой бота для чужих: /telegram:access policy allowlist')
  } else {
    say(`• Напиши боту @${name}: /help — справка, /setup — команды для терминала.`)
  }
  say('• Группа: добавь бота админом, включи «Темы», напиши в группе /id — бот пришлёт команду подключения.')
  say(`• Основная сессия: ${IS_WIN ? BAT : `${cfg.claudeExe} ${cfg.claudeArgs.join(' ')}`} (роутер и сам откроет её на первое сообщение в личку).`)
  say('• Telegram-сессии, запущенные до установки, перезапусти — они подхватят новый сервер.')
  return 0
}

async function status(): Promise<void> {
  say(`tg-topics ${PLUGIN_VERSION} — ${PLUGIN_ROOT}`)
  const token = readToken(cfg)
  const name = token ? await botName(token) : null
  say(`Бот:          ${!token ? '❌ токен не задан → /telegram:configure <токен>' : name ? `✅ @${name}` : '❌ токен не принят Telegram (или нет сети)'}`)

  const ov = overlayState(cfg)
  if (!ov.length) say('Плагин:       ❌ telegram@claude-plugins-official не установлен')
  for (const o of ov) say(`Плагин:       ${o.applied ? '✅' : '⚠️'} telegram ${o.version ?? ''} — оверлей ${o.applied ? 'применён' : 'НЕ применён → /tg-topics:setup'}`)

  const h = await health()
  if (!h) {
    say('Роутер:       ❌ не запущен → /tg-topics:router start')
  } else {
    say(`Роутер:       ${h.version === PLUGIN_VERSION ? '✅' : '⚠️'} работает${h.version ? ` (v${h.version}, pid ${h.pid})` : ' (старая версия → /tg-topics:router restart)'}`)
    try {
      const st = (await (await fetch(`${routerHttp(cfg)}/status`)).json()) as any
      const list = sessionRoutes(st)
      say(`Сессии:       ${list.length} из ${st.maxSessions ?? cfg.maxSessions} (закрыть: close N, лимит: max N)`)
      list.forEach((s, i) => say(`  ${i + 1}. ${s.starting ? '⏳' : '🟢'} ${s.label}${s.starting ? ' — запускается' : ` — ${st.sessions.find((c: any) => c.route === s.route)?.dir ?? ''}`}`))
      if (!list.length) say('  сессий нет — запустятся на первое сообщение')
    } catch {}
  }
  if (IS_WIN) say(`Автозапуск:   ${existsSync(STARTUP_VBS) ? '✅ при входе в Windows' : '❌ выключен → /tg-topics:router autostart on'}`)
  const marker = readJson(join(cfg.telegramStateDir, COMMANDS_MARKER))
  say(`Меню команд:  ${marker?.username ? `✅ @${marker.username}, ${String(marker.at ?? '').slice(0, 10)}` : '⚠️ ещё не записано → /tg-topics:router commands'}`)
  const a = loadAccess()
  say(`Доступ:       личка — ${a.dmPolicy}, людей: ${a.allowFrom.length}, групп: ${Object.keys(a.groups).length}${Object.keys(a.pending ?? {}).length ? `, ждут кода: ${Object.keys(a.pending!).length}` : ''}`)
  say(`Конфиг:       ${existsSync(CONFIG_FILE) ? CONFIG_FILE : '❌ нет → /tg-topics:setup'}`)
  say(`Лог:          ${LOG_FILE}`)
}

async function hookStart(): Promise<void> {
  // Quiet upkeep on every session start; does nothing before /tg-topics:setup.
  if (!existsSync(CONFIG_FILE)) return
  const changed = cfg.plugin.autoPatch ? applyOverlay(cfg).filter(r => r.changed) : []
  writeLaunchers()
  const h = await health()
  if (!h) {
    if (readToken(cfg)) await startRouter()
  } else if (h.version !== PLUGIN_VERSION) {
    // tg-topics was updated: hand over to the new router (sessions reconnect).
    await stopRouter()
    await startRouter()
  }
  if (changed.length) {
    say('[tg-topics] Обновил сервер Telegram-плагина (оверлей tg-topics). Если эта сессия работает с Telegram-каналом, перезапусти её, чтобы загрузить новую версию.')
  }
}

// ---- Main -----------------------------------------------------------------------------

const [cmd = 'status', ...rest] = process.argv.slice(2)
let code = 0
try {
  switch (cmd) {
    case 'setup':
      code = await setup(rest)
      break
    case 'status':
      await status()
      break
    case 'start':
      if (!readToken(cfg)) { say('❌ токен не задан → /telegram:configure <токен>'); code = 1; break }
      say((await startRouter()) ? '✅ роутер работает' : `❌ роутер не запустился — смотри ${LOG_FILE}`)
      break
    case 'stop':
      say((await stopRouter()) ? '✅ роутер остановлен (сессии остаются и переподключатся, когда он вернётся)' : '❌ не удалось остановить роутер')
      break
    case 'restart':
      await stopRouter()
      say((await startRouter()) ? '✅ роутер перезапущен' : `❌ роутер не запустился — смотри ${LOG_FILE}`)
      break
    case 'logs': {
      const n = Number(rest[0] ?? 40)
      try { say(readFileSync(LOG_FILE, 'utf8').trimEnd().split('\n').slice(-n).join('\n')) } catch { say(`лога пока нет: ${LOG_FILE}`) }
      break
    }
    case 'close':
      code = await closeSessions(rest[0])
      break
    case 'max':
      code = await maxSessions(rest[0])
      break
    case 'autostart':
      if (!IS_WIN) { say('автозапуск настраивается только на Windows; на macOS/Linux добавь `bun ' + LAUNCH_TS + '` в автозагрузку сам'); break }
      if (rest[0] === 'off') {
        rmSync(STARTUP_VBS, { force: true })
        say('✅ автозапуск выключен')
      } else {
        writeLaunchers()
        writeVbs(STARTUP_VBS, startVbs())
        say(`✅ автозапуск включён: ${STARTUP_VBS}`)
      }
      break
    case 'commands':
      say(await syncCommands(rest.includes('--force')))
      break
    case 'patch':
      for (const r of applyOverlay(cfg)) say(r.error ? `❌ ${r.dir}: ${r.error}` : `✅ ${r.dir}: ${r.changed ? 'применён' : 'уже применён'}`)
      break
    case 'unpatch': {
      const restored = removeOverlay(cfg)
      say(restored.length ? `✅ вернул оригинальный server.ts: ${restored.join(', ')}` : 'нечего возвращать (нет server.ts.upstream)')
      break
    }
    case 'guide': {
      const lang = rest[0] === 'en' ? 'en' : rest[0] === 'ru' ? 'ru' : langOf(process.env.LANG)
      say(setupGuide(lang, existsSync(join(cfg.telegramStateDir, 'access.json')) ? loadAccess() : undefined))
      break
    }
    case 'hook-start':
      try { await hookStart() } catch {}
      break
    default:
      say('команды: setup | status | start | stop | restart | logs [n] | close N|all | max [N] | autostart on|off | commands [--force] | patch | unpatch | guide [ru|en]')
      code = 1
  }
} catch (err) {
  if (cmd === 'hook-start') code = 0
  else {
    say(`❌ ${err}`)
    code = 1
  }
}
process.exit(code)
